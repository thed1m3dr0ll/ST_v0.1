// Списки пунктов из админки (обязанности, требования, условия, выполненные работы) хранятся одним текстом:
// каждый пункт — с новой строки. Превращаем текст в список: пустые строки выкидываем, маркеры в начале
// («•», «-», «—», «*», «1.», «1)»), если их поставили сами, убираем — на сайте маркеры рисуются стилями.
// Старый формат (массив строк) тоже понимаем.
export function lines(value: unknown): string[] {
  const raw = Array.isArray(value) ? value.map((v) => String(v ?? '')) : String(value ?? '').split(/\r?\n/);
  return raw
    .map((s) => s.trim().replace(/^(?:[•·\-–—*]|\d{1,2}[.)])\s+/, '').trim())
    .filter(Boolean);
}
